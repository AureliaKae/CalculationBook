export function genreSearchKeywords(genre) {
  return GENRE_WEB_KEYWORDS[genre] ?? [];
}

// stage: skeleton(数值/境界) | people(身份/地位) | catalog(外貌/细节)。
export function genreNote(genre, stage) {
  return GENRE_STAGE_NOTES[genre]?.[stage] ?? "";
}

export function guessGenreByKeywords(text) {
  const haystack = String(text ?? "");
  for (const [genre, pattern] of GENRE_PATTERNS) {
    if (pattern.test(haystack)) return genre;
  }
  return null;
}

// LLM 分类结果的归一化:合法题材才保留,否则回落 null 让启发式兜底。
export function normalizeGenre(value) {
  const genre = typeof value === "string" ? value.trim() : value?.genre;
  return GENRES.includes(genre) ? genre : null;
}
